import fs from 'node:fs';import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('./src/news.js',import.meta.url),'utf8');
const start=source.indexOf('export function recentReportingStrength(');
const end=source.indexOf('\nfunction markerTexture()',start);
assert(start>=0&&end>start);
const fn=Function(source.slice(start,end).replace('export function ','function ')+'\nreturn recentReportingStrength')();
const now=Date.parse('2026-10-19T00:00:00Z');
const member=t=>({articles:[{url:'https://example.org/story',published_at:t}]});
const near=h=>new Date(now-h*3600000).toISOString();
assert.equal(fn(member(near(1)),now),1);
assert.equal(fn(member(near(3)),now),1);
assert(Math.abs(fn(member(near(4.5)),now)-0.5)<.000001);
assert.equal(fn(member(near(6)),now),0);
assert.equal(fn(member(near(30)),now),0);
assert.equal(fn(member('not a date'),now),0);
assert.equal(fn({articles:[{url:'http://example.com',published_at:near(1)}]},now),0);
assert.equal(fn({members:[member(near(20)),member(near(1))]},now),1);
assert.equal(fn({},now),0);
assert.equal(fn(member(new Date(now+3600000).toISOString()),now),0);
console.log('10 freshness behavior assertions passed');
